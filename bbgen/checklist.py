"""The build checklist: parts first, then the wires group by group."""

from __future__ import annotations

from pathlib import Path

from .check import Result, wire_color, wire_nets
from .circuit import Circuit, End
from .parts import LEAD_KINDS, Part

# Where the pin-1 end (DIP notch, Pico USB) points, by rotation.
POINTS = {0: "left", 90: "up", 180: "right", 270: "down"}
RUNS = {0: "to the right", 90: "downward", 180: "to the left", 270: "upward"}


def _where(c: Circuit, part: Part) -> str:
    first = part.pins[0].hole
    at = f"`{c.hole_name(first)}`" if first else f"`{part.at}` (not placed)"
    if part.kind == "pico":
        return f"pin 1 in {at}, USB pointing {POINTS[part.rot]}{_keep_clear(c, part)}"
    if part.kind == "dip":
        return (f"pin 1 in {at}, notch (pin-1 end) pointing {POINTS[part.rot]}; "
                f"{len(part.pins)} pins, rows {part.width / 10:g} in apart")
    if part.kind == "sip":
        return f"pin 1 in {at}, pins running {RUNS[part.rot]}"
    if part.kind in LEAD_KINDS:
        legs = [f"`{c.hole_name(p.hole)}`" if p.hole else "?" for p in part.pins]
        polarity = {"electrolytic": " (+ leg first)", "diode": " (anode first)", "led": " (anode first)"}
        return f"legs in {legs[0]} and {legs[1]}{polarity.get(part.kind, '')}"
    return "off the breadboard: reached with flying leads"


def _keep_clear(c: Circuit, part: Part) -> str:
    """'; keep e1-e5 and f1-f5 clear for its USB cable', for the holes a part's keep-outs reserve."""
    out = []
    for what, _ in part.keepouts:
        holes = [h for h, who in c.occupied.items() if who == f"{part.ref}'s {what}"]
        rows: dict = {}
        for h in holes:
            rows.setdefault(h.row, []).append(h.col)
        spans = [f"`{r}{min(cols)}`-`{r}{max(cols)}`" if len(cols) > 1 else f"`{r}{cols[0]}`"
                 for r, cols in sorted(rows.items())]
        if spans:
            out.append(f"; keep {' and '.join(spans)} clear for its {what}")
    return "".join(out)


def _end(c: Circuit, result: Result, end: End) -> str:
    if end.pin is not None:
        return str(end.pin)
    if end.hole.is_rail:
        return f"{end.hole.row} rail"
    pins = result.strip_pins.get(c.boards[end.hole.board].strip(end.hole), [])
    return ", ".join(map(str, pins)) or "jumper junction"


def checklist(c: Circuit, result: Result) -> str:
    errors, warnings = result.errors, result.warnings
    out = [f"# {c.title}", "", f"Generated by bbgen from `{Path(c.source).name}`. Edit that file, not this one.", ""]
    out.append("**Wiring check: passed.**" if not errors else
               f"**Wiring check: {len(errors)} error(s). Fix these before building.**")
    if result.issues:
        out += ["", "## Check", ""]
        out += [f"- **{i.level}** `{i.code}`: {i.message}" for i in result.issues]
    if c.notes:
        out += ["", "## Notes", ""] + [f"- {n}" for n in c.notes]

    out += ["", "## Boards", ""]
    for b in c.boards.values():
        rails = []
        for rail in ("top+", "top-", "bot+", "bot-"):
            nets = sorted({n for h in b.holes() if h.row == rail
                           for n in result.nets_at(("strip", *b.strip(h)))})
            rails.append(f"`{rail}` {' / '.join(nets) or 'unused'}")
        split = ", rails split in the middle" if b.split_rails else ""
        out.append(f"- board {b.id}: {b.kind}-size{split}. Rails: {', '.join(rails)}")

    out += ["", "## Parts", "", "Place these first.", ""]
    for part in c.parts.values():
        name = " ".join(x for x in (part.title, part.value) if x) or part.kind
        out.append(f"- [ ] **{part.ref}** {name}: {_where(c, part)}")

    out += ["", "## Wires"]
    for group in c.groups:
        wires = [w for w in c.wires if w.group == group]
        if not wires:
            continue
        out += ["", f"### {group} ({len(wires)})", ""]
        for w in wires:
            if not (w.a and w.b):
                out.append(f"- [ ] **W{w.num}** `{w.spec[0]}` → `{w.spec[1]}`: could not be placed (see Check)")
                continue
            a = c.hole_name(w.a.hole) if w.a.hole else str(w.a.pin)
            b = c.hole_name(w.b.hole) if w.b.hole else str(w.b.pin)
            nets = " / ".join(wire_nets(c, result, w)) or "no net"
            bends = f", bent over {', '.join(f'`{v}`' for v in w.via)}" if w.via else ""
            out.append(f"- [ ] **W{w.num}** {wire_color(c, result, w)}: `{a}` → `{b}`{bends} · {nets} "
                       f"({_end(c, result, w.a)} ↔ {_end(c, result, w.b)})")
    return "\n".join(out) + "\n"
